"""Dev/test split of the hard questions, with every piece of required law listed per question.

    uv run python -m scripts.thesis.make_question_sets   # first (tiers)
    uv run python -m scripts.thesis.make_hard_set

The intrinsic `hard` + `very_hard` tiers (70 questions) are split, stratified by tier, into:

- `dev_hard`  (35) — for trying ideas cheaply: chunking, metadata, link-following, prompts. Tune on this.
- `test_hard` (35) — held out. Run only the finalists on it, once, to confirm the winner did not just fit
  the dev questions. Report final thesis numbers on all 141 (and on `test_hard`).

Both are added to question_sets.json (`--question-set dev_hard`). The script also writes
eval/results/thesis/hard_set.json and docs/hard_set.md: per question, each required provision with its type,
title, size, and whether the baseline / best stack retrieved it.

Use the required-law lists to *analyse* failures. Don't use them to decide which documents to re-chunk or
re-enrich: improving only the gold provisions (and not their distractors) leaks the answers into the
index. Corpus changes go to the whole corpus; the hard set is only where you measure them.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

import tiktoken

from app.config import settings
from app.datasets.gst.corpus_loader import load_corpus
from app.datasets.gst.document_mapper import source_label
from app.datasets.gst.golden_loader import load_golden_set
from app.services.gst_graph import kind
from eval.gst_retrieval import gold_sets, source_matches
from scripts.thesis.make_question_sets import QUESTION_SETS
from scripts.thesis.run_ablation import OUT_DIR

SEED = 11
OUT_JSON = Path("eval/results/thesis/hard_set.json")
OUT_MD = Path("docs/hard_set.md")
COMPARE = {"baseline": "hybrid_tfidf", "best": "large_top8_cap3"}


def main() -> None:
    qs = json.loads(QUESTION_SETS.read_text(encoding="utf-8"))
    rng = random.Random(SEED)
    dev, test = [], []
    for tier in ("hard", "very_hard"):
        ids = sorted(qs["sets"][f"tier_{tier}"])
        rng.shuffle(ids)
        half = len(ids) // 2 + len(ids) % 2 * (tier == "hard")
        dev += ids[:half]
        test += ids[half:]
    qs["sets"]["dev_hard"], qs["sets"]["test_hard"] = sorted(dev), sorted(test)
    QUESTION_SETS.write_text(json.dumps(qs, indent=2), encoding="utf-8")

    enc = tiktoken.get_encoding("o200k_base")
    corpus = {r["id"]: r for r in load_corpus(settings.gst_corpus_path)}
    instruments: dict[str, dict] = {}
    for r in corpus.values():
        instruments.setdefault(r["instrument_id"], r)
    goldens = {g["id"]: g for g in load_golden_set(settings.gst_golden_path)}
    retrieved = {name: {r["id"]: r.get("retrieved_ids") or []
                        for r in json.loads((OUT_DIR / f"{cfg}.json").read_text(encoding="utf-8"))["rows"]}
                 for name, cfg in COMPARE.items()}

    def describe(gold_id: str) -> dict:
        if gold_id in corpus:
            r = corpus[gold_id]
            return {"id": gold_id, "kind": kind(r), "label": source_label(r), "title": r.get("provision_title") or "",
                    "law_tokens": len(enc.encode(r.get("raw_text") or ""))}
        r = instruments.get(gold_id)  # a whole notification/circular named as the source
        return {"id": gold_id, "kind": kind(r) if r else "unknown", "label": gold_id,
                "title": "(any entry of " + (r.get("instrument_title") or "this instrument") + ")" if r else "(any entry)", "law_tokens": None}

    out = []
    for qid in sorted(dev + test):
        g = goldens[qid]
        law = []
        for gid in gold_sets(g, "corrected")[0]:
            item = describe(gid)
            for name in COMPARE:
                item[f"found_{name}"] = any(source_matches(gid, rid) for rid in retrieved[name].get(qid, []))
            law.append(item)
        info = qs["questions"][qid]
        out.append({"id": qid, "set": "dev" if qid in dev else "test", "tier": info["tier"],
                    "question": g["question"], "required_law": law})
    OUT_JSON.write_text(json.dumps(out, indent=1, ensure_ascii=False), encoding="utf-8")

    law_ids = {item["id"] for q in out for item in q["required_law"]}
    kinds = {}
    for q in out:
        for item in q["required_law"]:
            kinds.setdefault(item["kind"], set()).add(item["id"])
    found = {n: sum(i[f"found_{n}"] for q in out for i in q["required_law"]) for n in COMPARE}
    total = sum(len(q["required_law"]) for q in out)

    md = ["# Hard question set (generated by scripts/thesis/make_hard_set.py)", "",
          __doc__.split("\n\n", 2)[2].split("\n\nBoth are added")[0], "",
          f"- **{len(dev)} dev / {len(test)} test** questions; {total} (question, required law) pairs; "
          f"{len(law_ids)} distinct provisions: " + ", ".join(f"{k} {len(v)}" for k, v in sorted(kinds.items())) + ".",
          f"- Required law retrieved: baseline {found['baseline']}/{total} ({found['baseline'] / total:.0%}), "
          f"best stack {found['best']}/{total} ({found['best'] / total:.0%}).",
          "- Columns B / S: found by the baseline / best stack (✓ / ·). Tokens = plain law text.", ""]
    for q in out:
        md += [f"## {q['id']} — {q['set']}, {q['tier']}", "", "> " + " ".join(q["question"].split())[:600]
               + ("…" if len(q["question"]) > 600 else ""), "",
               "| Type | Provision | Title | Tokens | B | S |", "|---|---|---|---|---|---|"]
        md += [f"| {i['kind']} | {i['label']} | {i['title'][:70]} | {i['law_tokens'] or '—'} | "
               f"{'✓' if i['found_baseline'] else '·'} | {'✓' if i['found_best'] else '·'} |" for i in q["required_law"]]
        md.append("")
    OUT_MD.write_text("\n".join(md), encoding="utf-8")
    print(f"dev_hard {len(dev)}, test_hard {len(test)}; {len(law_ids)} distinct required provisions "
          f"({', '.join(f'{k} {len(v)}' for k, v in sorted(kinds.items()))}); found baseline {found['baseline']}/{total}, "
          f"best {found['best']}/{total}\nWrote {OUT_JSON}, {OUT_MD}, and sets dev_hard/test_hard in {QUESTION_SETS}")


if __name__ == "__main__":
    main()
