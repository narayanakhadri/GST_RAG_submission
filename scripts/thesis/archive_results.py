"""Archive every eval result into git-tracked, compressed files and write an index for the thesis.

    uv run python -m scripts.thesis.archive_results

The full RAGAS run files in eval/results/*.json are 5–14 MB each and git-ignored. This copies each one (and
each Qwen re-score) gzipped into eval/results/thesis/archive/ (≈10× smaller, tracked by git), then writes
eval/results/thesis/RESULTS_INDEX.md: one line per run with its settings, judge and headline numbers.
Re-run it after every new run; files already archived and unchanged are skipped. Read an archived file with
`scripts.thesis.archive_results.read_json(path)`, which handles .json and .json.gz alike.
"""

from __future__ import annotations

import gzip
import json
from pathlib import Path

RESULTS = Path("eval/results")
ARCHIVE = RESULTS / "thesis" / "archive"
INDEX = RESULTS / "thesis" / "RESULTS_INDEX.md"


def read_json(path: str | Path) -> dict:
    path = Path(path)
    if not path.exists() and path.suffix == ".json" and (gz := ARCHIVE / (path.name + ".gz")).exists():
        path = gz  # the uncompressed run file may only exist on the machine that produced it
    raw = gzip.decompress(path.read_bytes()) if path.suffix == ".gz" else path.read_bytes()
    return json.loads(raw.decode("utf-8"))


def archive() -> list[Path]:
    ARCHIVE.mkdir(parents=True, exist_ok=True)
    done = []
    for src in sorted(RESULTS.glob("*.json")):
        if src.name.endswith(".partial.json"):
            continue  # an unfinished re-score; archived once it completes
        dst = ARCHIVE / (src.name + ".gz")
        if not dst.exists() or dst.stat().st_mtime < src.stat().st_mtime:
            dst.write_bytes(gzip.compress(src.read_bytes(), compresslevel=9, mtime=0))
        done.append(dst)
    return done


def _fmt(v) -> str:
    return "—" if v is None else f"{v:.3f}" if isinstance(v, float) else str(v)


def index(paths: list[Path]) -> str:
    lines = ["# Results index (generated by scripts/thesis/archive_results.py)", "",
             "Every eval run, archived gzipped in `eval/results/thesis/archive/`. RAGAS columns are means over the run's",
             "rows; retrieval columns are required-law recall / MRR on fully covered questions, corrected gold.",
             "Retrieval-ablation results (one file per configuration) are in `eval/results/thesis/retrieval/`, and",
             "the generated thesis tables in `eval/results/thesis/results_tables.md`.", "",
             "| File | Profile | Judge | Metrics | Question set | n | Faithfulness | Answer relevancy | "
             "Context precision | Context recall | Recall | MRR |",
             "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for p in paths:
        try:
            d = read_json(p)
        except (OSError, ValueError):
            continue
        if "rows" not in d:
            lines.append(f"| {p.name} | (token usage / other) | | | | | | | | | | |")
            continue
        agg = d.get("aggregate") or {}
        judge = (d.get("ragas_judge") or {}).get("model") or ("gpt-4o-mini" if "ragas_metrics" not in d and agg.get("faithfulness") is not None else "—")
        full = ((d.get("coverage_split") or {}).get("corrected") or {}).get("full") or {}
        lines.append(" | ".join([
            f"| {p.name.removesuffix('.gz')}", str(d.get("profile") or d.get("name") or ""), judge,
            str(d.get("ragas_metrics") or ("all four" if agg.get("context_precision") is not None else "—")),
            str(d.get("question_set") or "—"), str(len(d["rows"])),
            _fmt(agg.get("faithfulness")), _fmt(agg.get("answer_relevancy")), _fmt(agg.get("context_precision")),
            _fmt(agg.get("context_recall")), _fmt(full.get("required_recall")), _fmt(full.get("required_mrr")),
        ]) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    paths = archive()
    INDEX.write_text(index(paths), encoding="utf-8")
    size = sum(p.stat().st_size for p in paths) / 1e6
    print(f"Archived {len(paths)} result files ({size:.1f} MB gzipped) in {ARCHIVE}\nWrote {INDEX}")


if __name__ == "__main__":
    main()
